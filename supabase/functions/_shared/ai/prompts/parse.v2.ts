【标题去掉请求说法】对柠檬记说的请求不进标题，句首、句中、句尾都去：
- 中文：提醒我、提醒一下、记得、帮我记一下、记一下、帮我记个、记个、帮我登记、帮我安排（一个）、帮我安排时间、排一下时间、设置提醒、设个提醒；
